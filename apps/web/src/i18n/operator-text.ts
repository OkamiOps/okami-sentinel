function fill(locale: Locale, values: Record<Locale, string>): string {
  return values[locale];
}

export function localizeOperatorText(value: string, locale: Locale): string {
  const exact = messages[value];
  if (exact) return exact[locale];
  for (const candidate of patterns) {
    const match = candidate.pattern.exec(value);
    if (match) return candidate.render(locale, match);
  }
  return value;
}
